function write_geo(geoPath, geom, cfg)
%WRITE_GEO Write a 2D Gmsh geometry and mesh-size fields for SU2 export.
%   WRITE_GEO(GEOPATH, GEOM, CFG) writes a .geo text file. GEOM is the
%   output of geometry.naca4; CFG is the validated configuration accepted
%   by generate_naca_mesh. All dimensions use the unit of CFG.chord.
%   The outer loop is CCW and the airfoil hole is CW. Physical groups are
%   airfoil (wall), farfield (outer boundary), and fluid (surface).

[fid, message] = fopen(geoPath, 'w');
if fid < 0
    error('PROJECT_CFD:GeoWriteFailed', ...
        'Cannot open Gmsh geometry file %s: %s', geoPath, message);
end
cleanupFile = onCleanup(@() fclose(fid)); %#ok<NASGU>

n = size(geom.contour, 1);
fprintf(fid, '// NACA %s, chord %.16g (closed trailing edge)\n', ...
    geom.code, geom.chord);
fprintf(fid, '// Generated by PROJECT_CFD. Lengths use the chord unit.\n');
fprintf(fid, 'SetFactory("Built-in");\n\n');
for k = 1:n
    fprintf(fid, 'Point(%d) = {%.16g, %.16g, 0, %.16g};\n', ...
        k, geom.contour(k,1), geom.contour(k,2), cfg.hNear);
end

% Upper: TE -> LE. Lower: LE -> TE, reusing both edge points.
fprintf(fid, '\nSpline(1) = {%s};\n', idList(1:geom.nPoints));
lowerIds = [geom.leadingEdgeId, geom.nPoints+1:n, geom.trailingEdgeId];
fprintf(fid, 'Spline(2) = {%s};\n\n', idList(lowerIds));

centerId = n + 1;
outerIds = n + (2:5); % right, top, left, bottom
cx = cfg.domainCenter(1);
cy = cfg.domainCenter(2);
r = cfg.domainRadius;
coords = [cx,cy; cx+r,cy; cx,cy+r; cx-r,cy; cx,cy-r];
for k = 1:5
    pointId = n + k;
    fprintf(fid, 'Point(%d) = {%.16g, %.16g, 0, %.16g};\n', ...
        pointId, coords(k,1), coords(k,2), cfg.hFar);
end
for k = 1:4
    next = mod(k,4) + 1;
    fprintf(fid, 'Circle(%d) = {%d, %d, %d};\n', ...
        k+2, outerIds(k), centerId, outerIds(next));
end

fprintf(fid, '\nCurve Loop(1) = {3, 4, 5, 6};\n');
fprintf(fid, 'Curve Loop(2) = {-2, -1};\n');
fprintf(fid, 'Plane Surface(1) = {1, 2};\n\n');
fprintf(fid, 'Physical Curve("airfoil") = {1, 2};\n');
fprintf(fid, 'Physical Curve("farfield") = {3, 4, 5, 6};\n');
fprintf(fid, 'Physical Surface("fluid") = {1};\n\n');

% Size is smallest on the wall and at both sharp/strong-curvature edges.
fprintf(fid, 'Field[1] = Distance;\n');
fprintf(fid, 'Field[1].CurvesList = {1, 2};\n');
fprintf(fid, 'Field[1].Sampling = 200;\n');
fprintf(fid, 'Field[2] = Threshold;\n');
fprintf(fid, 'Field[2].InField = 1;\n');
fprintf(fid, 'Field[2].SizeMin = %.16g;\n', cfg.hNear);
fprintf(fid, 'Field[2].SizeMax = %.16g;\n', cfg.hFar);
fprintf(fid, 'Field[2].DistMin = %.16g;\n', cfg.dMin);
fprintf(fid, 'Field[2].DistMax = %.16g;\n', cfg.dMax);
fprintf(fid, 'Field[3] = Distance;\n');
fprintf(fid, 'Field[3].PointsList = {%d, %d};\n', ...
    geom.leadingEdgeId, geom.trailingEdgeId);
fprintf(fid, 'Field[4] = Threshold;\n');
fprintf(fid, 'Field[4].InField = 3;\n');
fprintf(fid, 'Field[4].SizeMin = %.16g;\n', cfg.hEdge);
fprintf(fid, 'Field[4].SizeMax = %.16g;\n', cfg.hFar);
fprintf(fid, 'Field[4].DistMin = %.16g;\n', cfg.edgeDMin);
fprintf(fid, 'Field[4].DistMax = %.16g;\n', cfg.edgeDMax);
fprintf(fid, 'Field[5] = Min;\n');
fprintf(fid, 'Field[5].FieldsList = {2, 4};\n');
fprintf(fid, 'Background Field = 5;\n\n');
fprintf(fid, 'Mesh.MeshSizeFromPoints = 0;\n');
fprintf(fid, 'Mesh.MeshSizeFromCurvature = 0;\n');
fprintf(fid, 'Mesh.MeshSizeExtendFromBoundary = 0;\n');
fprintf(fid, 'Mesh.MeshSizeMin = %.16g;\n', cfg.hEdge);
fprintf(fid, 'Mesh.MeshSizeMax = %.16g;\n', cfg.hFar);
fprintf(fid, 'Mesh.Algorithm = 6; // Frontal-Delaunay triangles\n');
fprintf(fid, 'Mesh.ElementOrder = 1;\n');
end

function str = idList(ids)
str = sprintf('%d, ', ids);
str = str(1:end-2);
end
